  avatar_id text,
  body text,
  created_at timestamptz,
  can_delete boolean
)
language sql
security definer
stable
set search_path = public
as $$
  select
    comment.id,
    comment.user_id,
    coalesce(profile.username, 'lector'),
    profile.avatar_id,
