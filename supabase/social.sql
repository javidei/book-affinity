create or replace function public.book_affinity_add_comment(p_book_id uuid, p_body text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_body text := trim(coalesce(p_body, ''));
  v_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para comentar.' using errcode = '42501';
  end if;

  if not public.book_affinity_can_view_published_book(p_book_id) then
    raise exception 'No puedes comentar este libro privado.' using errcode = '42501';
  end if;

  if char_length(v_body) not between 1 and 1000 then
    raise exception 'El comentario debe tener entre 1 y 1000 caracteres.' using errcode = '22023';
  end if;

  insert into public.book_affinity_comments (book_id, user_id, body)
  values (p_book_id, auth.uid(), v_body)
  returning id into v_id;

  return v_id;
end;
$$;

create or replace function public.book_affinity_delete_comment(p_comment_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión.' using errcode = '42501';
  end if;

  delete from public.book_affinity_comments as comment
  using public.books as book
  where comment.id = p_comment_id
    and book.id = comment.book_id
    and (comment.user_id = auth.uid() or book.user_id = auth.uid());

  return found;
end;
$$;

