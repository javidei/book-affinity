create or replace function public.book_affinity_can_view_published_book(p_book_id uuid)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1
    from public.books as book
    where book.id = p_book_id
      and book.is_public = true
      and (
        book.user_id = auth.uid()
        or exists (
          select 1
          from public.book_affinity_follows as follow
          where follow.follower_id = auth.uid()
            and follow.followed_id = book.user_id
        )
      )
  );
$$;

create or replace function public.book_affinity_set_my_avatar(p_avatar_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_avatar text := nullif(trim(coalesce(p_avatar_id, '')), '');
begin
  if v_user_id is null then
    raise exception 'Debes iniciar sesión para cambiar el icono.' using errcode = '42501';
  end if;

  if v_avatar is not null and v_avatar not in (
    'literary-crest', 'minimal-reader', 'moon-book', 'book-shield', 'retro-reader'
  ) then
    raise exception 'El icono seleccionado no existe.' using errcode = '22023';
  end if;

  insert into public.book_affinity_profiles (user_id, avatar_id)
  values (v_user_id, v_avatar)
  on conflict (user_id) do update
    set avatar_id = excluded.avatar_id,
        updated_at = now();

  return jsonb_build_object('user_id', v_user_id, 'avatar_id', v_avatar);
end;
$$;

create or replace function public.book_affinity_find_reader(p_username text)
returns jsonb
language plpgsql
security definer
stable
set search_path = public
as $$
declare
  v_username text := lower(trim(coalesce(p_username, '')));
  v_profile public.book_affinity_profiles%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para buscar lectores.' using errcode = '42501';
  end if;

  if v_username !~ '^[a-z0-9_]{3,24}$' then
    return null;
  end if;

  select * into v_profile
  from public.book_affinity_profiles
  where username_normalized = v_username;

  if not found then return null; end if;

  return jsonb_build_object(
    'user_id', v_profile.user_id,
    'username', v_profile.username,
    'avatar_id', v_profile.avatar_id,
    'is_me', v_profile.user_id = auth.uid(),
    'is_following', exists (
      select 1 from public.book_affinity_follows
      where follower_id = auth.uid() and followed_id = v_profile.user_id
    ),
    'followers_count', (
      select count(*) from public.book_affinity_follows where followed_id = v_profile.user_id
    ),
    'following_count', (
      select count(*) from public.book_affinity_follows where follower_id = v_profile.user_id
    ),
    'published_reading_count', (
      select count(*) from public.books
      where user_id = v_profile.user_id and is_public = true and status = 'reading'
    )
  );
end;
$$;

create or replace function public.book_affinity_follow_reader(p_username text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_target uuid;
  v_username text := lower(trim(coalesce(p_username, '')));
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para seguir lectores.' using errcode = '42501';
  end if;

  select user_id into v_target
  from public.book_affinity_profiles
  where username_normalized = v_username;

  if v_target is null then
    raise exception 'No existe ningún lector con ese usuario.' using errcode = 'P0002';
  end if;

  if v_target = auth.uid() then
    raise exception 'No puedes seguirte a ti mismo.' using errcode = '22023';
  end if;

  insert into public.book_affinity_follows (follower_id, followed_id)
  values (auth.uid(), v_target)
  on conflict do nothing;

  return public.book_affinity_find_reader(v_username);
end;
$$;

create or replace function public.book_affinity_unfollow_reader(p_user_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión.' using errcode = '42501';
  end if;

  delete from public.book_affinity_follows
  where follower_id = auth.uid() and followed_id = p_user_id;

  return found;
end;
$$;

create or replace function public.book_affinity_list_following()
returns table (
  user_id uuid,
  username text,
  avatar_id text,
  followed_at timestamptz,
  published_reading_count bigint
)
language sql
security definer
stable
set search_path = public
as $$
  select
    profile.user_id,
    profile.username,
    profile.avatar_id,
    follow.created_at,
    count(book.id) filter (where book.is_public = true and book.status = 'reading')
  from public.book_affinity_follows as follow
  join public.book_affinity_profiles as profile on profile.user_id = follow.followed_id
  left join public.books as book on book.user_id = profile.user_id
  where follow.follower_id = auth.uid()
  group by profile.user_id, profile.username, profile.avatar_id, follow.created_at
  order by lower(profile.username);
$$;

create or replace function public.book_affinity_list_followers()
returns table (
  user_id uuid,
  username text,
  avatar_id text,
  followed_at timestamptz,
  is_following_back boolean
)
language sql
security definer
stable
set search_path = public
as $$
  select
    profile.user_id,
    profile.username,
    profile.avatar_id,
    follow.created_at,
    exists (
      select 1 from public.book_affinity_follows as reciprocal
      where reciprocal.follower_id = auth.uid()
        and reciprocal.followed_id = profile.user_id
    )
  from public.book_affinity_follows as follow
  join public.book_affinity_profiles as profile on profile.user_id = follow.follower_id
  where follow.followed_id = auth.uid()
  order by lower(profile.username);
$$;

